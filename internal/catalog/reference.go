func BandFor(value int) Band {
	if value <= ReferenceBands[0].Band {
		return ReferenceBands[0]
	}
	for _, b := range ReferenceBands {
		if value <= b.Band {
			return b
		}
	}
	return ReferenceBands[len(ReferenceBands)-1]
}

func SortedBands() []Band {
	out := append([]Band{}, ReferenceBands...)
	sort.Slice(out, func(i, j int) bool { return out[i].Band < out[j].Band })
	return out
}

func WeightTotal() float64 {
	total := 0.0
	for _, b := range ReferenceBands {
		total += b.Weight
	}
	return total
}
